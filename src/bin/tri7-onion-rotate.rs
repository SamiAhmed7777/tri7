/// The ACTUAL serving list, from live connections — logged on every
/// transition (and every tick), never a bare "stays live" claim.
fn log_serving(st: &OnionState, current_live: bool, previous_live: bool) {
    for (addr, live) in serving_set(st, current_live, previous_live) {
        if live {
            log(&format!(
                "SERVING {} — control connection held by this process",
                addr
            ));
        } else {
            log(&format!(
                "NOT SERVING {} — announced but not held (no stored key / re-establish failed)",
                addr
            ));
        }
    }
}

/// Probe one held connection with a cheap GETINFO. A dead connection means
/// tor restarted and destroyed the service it held — the connection is
/// dropped here so the caller can re-establish from the stored key.
fn probe_conn(conn: &mut Option<ControlConn>, label: &str) -> bool {
    match conn {
        Some(c) => match c.command("GETINFO version") {
            Ok(_) => true,
            Err(e) => {
                log(&format!(
                    "{} control connection DIED ({}): the service it held is GONE — re-establishing from the stored key",
                    label, e
                ));
                *conn = None;
                false
            }
        },
        None => false,
    }
}

/// `DEL_ONION` on a held connection (best effort — dropping the connection
/// kills an ephemeral service anyway).
fn del_onion_on_conn(conn: &mut ControlConn, onion_address: &str) {
    let id = onion_address.strip_suffix(".onion").unwrap_or(onion_address);
    if let Err(e) = conn.command(&format!("DEL_ONION {}", id)) {
        log(&format!(
            "DEL_ONION {} failed ({}) — dropping the connection instead (an ephemeral service dies with it)",
            onion_address, e
        ));
    }
}

/// Re-establish ONE stored service on a fresh KEPT control connection from
/// its stored private key. Refuses to hold a different ServiceID than the
/// address we meant to serve.
fn establish_service(
    args: &Args,
    auth_src: &AuthSource,
    addr: &str,
    key: &str,
) -> Option<ControlConn> {
    // fresh connection → the auth line is built NOW (cookie re-read), so a
    // tor restart's regenerated cookie is picked up here
    let auth = match auth_for_connection(auth_src) {
        Ok(a) => a,
        Err(e) => {
            log(&format!(
                "{}: control auth failed ({}) — NOT SERVING {}",
                addr, e, addr
            ));
            return None;
        }
    };
    let mut c = match open_control(&args.control, &auth) {
        Ok(c) => c,
        Err(e) => {
            log(&format!(
                "{}: control connect failed ({}) — NOT SERVING {}",
                addr, e, addr
            ));
            return None;
        }
    };
    match c.command(&add_onion_with_key_line(args.port, key)) {
        Ok(reply) => match service_id_from_reply(&reply) {
            Ok(id) if format!("{}.onion", id) == addr => {
                log(&format!(
                    "{} re-established from its stored key — held open",
                    addr
                ));
                Some(c)
            }
            Ok(id) => {
                log(&format!(
                    "{}: tor returned ServiceID {} instead — refusing to hold the wrong service; NOT SERVING {}",
                    addr, id, addr
                ));
                None
            }
            Err(e) => {
                log(&format!(
                    "{}: unparseable re-establish reply ({}) — NOT SERVING {}",
                    addr, e, addr
                ));
                None
            }
        },
        Err(e) => {
            log(&format!(
                "{}: ADD_ONION with the stored key failed ({}) — NOT SERVING {}",
                addr, e, addr
            ));
            None
        }
    }
}

/// Create a FRESH hidden service on a new KEPT control connection.
/// Returns `(address, private_key_from_reply, connection)`.
fn create_service(
    args: &Args,
    auth_src: &AuthSource,
) -> Result<(String, Option<String>, ControlConn), String> {
    // fresh connection → fresh auth line (cookie re-read at connect time)
    let auth = auth_for_connection(auth_src)?;
    let mut c = open_control(&args.control, &auth)?;
    let reply = c.command(&add_onion_line(args.port))?;
    let id = service_id_from_reply(&reply)?;
    let key = private_key_from_reply(&reply);
    if key.is_none() {
        log(&format!(
            "ADD_ONION ok: ServiceID {} (no PrivateKey in reply — this address CANNOT be re-established after a restart)",
            id
        ));
    } else {
        log(&format!("ADD_ONION ok: ServiceID {}", id));
    }
    Ok((format!("{}.onion", id), key, c))
}

/// Sign, self-verify and PRINT a rotation announcement (shared by the
/// bootstrap, the startup repair and in-process rotations).
fn announce_rotation(
    secret: &[u8; 32],
    pub_hex: &str,
    old_onion: &str,
    new_onion: &str,
    now: u64,
    valid_until: u64,
) -> Result<RotationAnnouncement, String> {
    let mut ann = RotationAnnouncement {
        identity_pub: pub_hex.to_string(),
        old_onion: old_onion.to_string(),
        new_onion: new_onion.to_string(),
        epoch: now,
        valid_from: now,
        valid_until,
        sig: String::new(),
    };
    sign_announcement(secret, &mut ann)?;
    verify_announcement(&ann, Some(now))?;
    println!(
        "{}",
        serde_json::to_string_pretty(&ann).unwrap_or_else(|_| "{}".into())
    );
    println!("ANNOUNCE {} {}", new_onion, ann.sig);
    Ok(ann)
}

/// One IN-PROCESS rotation (the pure `apply_rotation` transition plus the
/// control-port work it needs):
///   1. `ADD_ONION` a new service on a fresh KEPT connection;
///   2. build the next state — the outgoing current becomes previous
///      TOGETHER WITH `current_key` → `previous_key`;
///   3. sign + self-verify + print the announcement and persist FIRST —
///      on any failure the new connection is dropped (its service dies)
///      and the old services are untouched, so the next tick retries
///      cleanly;
///   4. only then commit the connections: any displaced previous is
///      `DEL_ONION`ed with its connection, the outgoing current's
///      connection becomes the previous's connection (the old address
///      never blinks), and the new connection becomes current.
#[allow(clippy::too_many_arguments)]
fn rotate_in_process(
    args: &Args,
    auth_src: &AuthSource,
    secret: &[u8; 32],
    pub_hex: &str,
    st: &OnionState,
    cur_conn: &mut Option<ControlConn>,
    prev_conn: &mut Option<ControlConn>,
    now: u64,
    grace_days: u64,
    state_path: &std::path::Path,
) -> Result<OnionState, String> {
    let (new_addr, new_key, new_conn) = create_service(args, auth_src)?;
    let mut next = apply_rotation(st, new_addr, new_key, now, grace_days);
    next.identity_pub = pub_hex.to_string();
    if let Err(e) =
        announce_rotation(secret, pub_hex, &st.current, &next.current, now, next.grace_until)
    {
        return Err(e); // new_conn dropped here: its service dies, nothing half-done
    }
    if let Err(e) = next.save(state_path) {
        return Err(format!("save state: {} (the new service dies with its connection; retrying next tick)", e));
    }
    log(&format!("state written: {}", state_path.display()));
    // commit the connections LAST — from here the rotation is done
    if let Some(old_prev) = st.previous.clone() {
        if let Some(mut c) = prev_conn.take() {
            del_onion_on_conn(&mut c, &old_prev);
        }
    }
    *prev_conn = cur_conn.take();
    *cur_conn = Some(new_conn);
    Ok(next)
}

/// The lifecycle daemon: runs until killed, never exits for being due.
fn hold_daemon(
    args: &Args,
    auth_src: &AuthSource,
    state_dir: &std::path::Path,
    state_path: &std::path::Path,
) {
    if let Err(e) = std::fs::create_dir_all(state_dir) {
        eprintln!("FAIL({}): create_dir_all {}: {}", EXIT_FAIL, state_dir.display(), e);
        std::process::exit(EXIT_FAIL);
    }
    let (secret, pub_hex) = identity_or_exit(state_dir);
    let mut cur_conn: Option<ControlConn> = None;
    let mut prev_conn: Option<ControlConn> = None;

    // Startup: ALWAYS bring the stored services back (round-3 defect 3) —
    // whether or not a rotation is due. Bootstrapping and repair-rotation
    // failures exit non-zero so systemd's Restart=always retries in 15s.
    let mut st = match OnionState::load(state_path) {
        None => {
            log("no onion state yet — bootstrapping the FIRST current service");
            let now = now_secs();
            let (addr, key, conn) = match create_service(args, auth_src) {
                Ok(x) => x,
                Err(e) => {
                    eprintln!("FAIL({}): bootstrap ADD_ONION: {}", EXIT_FAIL, e);
                    std::process::exit(EXIT_FAIL);
                }
            };
            cur_conn = Some(conn);
            let st = OnionState {
                current: addr.clone(),
                previous: None,
                rotated_at: now,
                // A first run has nothing in grace, but the announcement still
                // needs a REAL window: an announcement whose valid_until equals
                // its valid_from is rejected by validation, which used to make a
                // fresh install exit before it ever saved state (restart loop).
                grace_until: now + args.grace_days.saturating_mul(86_400),
                identity_pub: pub_hex.clone(),
                current_key: key,
                previous_key: None,
            };
            if let Err(e) = announce_rotation(&secret, &pub_hex, &st.current, &st.current, now, st.grace_until) {
                eprintln!("FAIL({}): bootstrap announcement: {}", EXIT_FAIL, e);
                std::process::exit(EXIT_FAIL);
            }
            if let Err(e) = st.save(state_path) {
                eprintln!("FAIL({}): save state: {}", EXIT_FAIL, e);
                std::process::exit(EXIT_FAIL);
            }
            log(&format!("state written: {}", state_path.display()));
            st
        }
        Some(old) if startup_needs_rotation(&old) => {
            log(&format!(
                "current {} has NO stored key — it can never be re-established after a tor restart; rotating NOW to restore service (the one-shot period gate does not apply to this repair)",
                old.current
            ));
            let now = now_secs();
            match rotate_in_process(
                args, auth_src, &secret, &pub_hex, &old, &mut cur_conn, &mut prev_conn, now,
                args.grace_days, state_path,
            ) {
                Ok(next) => next,
                Err(e) => {
                    eprintln!("FAIL({}): repair rotation: {}", EXIT_FAIL, e);
                    std::process::exit(EXIT_FAIL);
                }
            }
        }
        Some(old) => {
            let now = now_secs();
            let st = old;
            // plan_startup is deterministic: current first, then previous
            // while its grace window is open — each from its OWN key.
            for svc in plan_startup(&st, now) {
                let ServiceToServe { address, key } = &svc;
                let established = match key {
                    Some(k) => establish_service(args, auth_src, address, k),
                    None => {
                        log(&format!(
                            "{}: NO stored key — its ephemeral service died with the prior process; announced but NOT SERVING. Persistent alternative: torrc HiddenServiceDir + --hostname-file",
                            address
                        ));
                        None
                    }
                };
                if *address == st.current {
                    cur_conn = established;
                } else {
                    prev_conn = established;
                }
            }
            st
        }
    };

    log(&format!(
        "lifecycle daemon running: re-establishes stored services from their keys, rotates IN-PROCESS every {} days when due (grace {} days), ticks every {}s — never exits for being due",
        onion::ROTATION_PERIOD_DAYS,
        args.grace_days,
        HOLD_TICK_SECS
    ));
    log_serving(&st, cur_conn.is_some(), prev_conn.is_some());

    loop {
        // probe the held connections; re-establish dead slots from keys
        let cur_alive = probe_conn(&mut cur_conn, "current");
        let now = now_secs();
        let prev_in_grace = st.previous.is_some() && st.grace_active(now);
        let prev_alive = probe_conn(&mut prev_conn, "previous");

        if !cur_alive {
            match st.current_key.clone() {
                Some(k) => {
                    if let Some(c) = establish_service(args, auth_src, &st.current, &k) {
                        cur_conn = Some(c);
                    }
                }
                None => log(
                    "current: NO stored key — cannot be re-established; NOT SERVING until the next in-process rotation",
                ),
            }
        }
        if prev_in_grace && !prev_alive {
            if let (Some(prev), Some(k)) = (st.previous.clone(), st.previous_key.clone()) {
                if let Some(c) = establish_service(args, auth_src, &prev, &k) {
                    prev_conn = Some(c);
                }
            }
        }

        // the tick plan decides; there is no exit in a TickPlan
        let plan = plan_tick(&st, now_secs(), onion::ROTATION_PERIOD_DAYS, args.grace_days);

        if let Some(prev_addr) = plan.retire_previous.clone() {
            log(&format!(
                "grace window over — retiring previous {} (clearing previous and previous_key from state)",
                prev_addr
            ));
            if let Some(mut c) = prev_conn.take() {
                del_onion_on_conn(&mut c, &prev_addr);
            }
            st = apply_retire(&st);
            match st.save(state_path) {
                Ok(()) => log(&format!("state written: {}", state_path.display())),
                Err(e) => log(&format!(
                    "save state after retire failed ({}) — will be retried by the next transition",
                    e
                )),
            }
        }

        if plan.rotate {
            // IN-PROCESS rotation — the daemon carries on (defect 2: no exit)
            match rotate_in_process(
                args, auth_src, &secret, &pub_hex, &st, &mut cur_conn, &mut prev_conn,
                now_secs(), plan.grace_days, state_path,
            ) {
                Ok(next) => {
                    st = next;
                    log(&format!(
                        "rotation done: new onion {} — previous {} in grace until {}",
                        st.current,
                        st.previous.as_deref().unwrap_or("-"),
                        onion::utc_date_string(st.grace_until)
                    ));
                }
                Err(e) => log(&format!(
                    "in-process rotation FAILED ({}) — still holding the current services; retrying on the next tick",
                    e
                )),
            }
        }

        // the ACTUAL serving list after this tick's work
        log_serving(&st, cur_conn.is_some(), prev_conn.is_some());
        std::thread::sleep(std::time::Duration::from_secs(HOLD_TICK_SECS));
    }
}

fn retire(args: &Args, auth_src: &AuthSource, state_path: &std::path::Path, now: u64) {
    let Some(st) = OnionState::load(state_path) else {
        eprintln!(
            "FAIL({}): no onion state at {} — nothing to retire",
            EXIT_FAIL,
            state_path.display()
        );
        std::process::exit(EXIT_FAIL);
    };
    let Some(previous) = st.previous.clone() else {
        log("no previous address in state — nothing to retire");
        return;
    };
    // Round 2 item 2: DEL_ONION only AFTER grace_until — refused earlier.
    if st.grace_active(now) {
        log(&format!(
            "grace window still open ({} secs left, until {}) — refusing to retire {}",
            st.grace_until - now,
            onion::utc_date_string(st.grace_until),
            previous
        ));
        return;
    }
    if !args.dry_run {
        // the ONE connection this one-shot opens: auth line built NOW
        let auth = match auth_for_connection(auth_src) {
            Ok(a) => a,
            Err(e) => {
                eprintln!("FAIL({}): {}", EXIT_FAIL, e);
                std::process::exit(EXIT_FAIL);
            }
        };
        match onion::retire_onion_with_auth(&args.control, &auth, &previous) {
            Ok(()) => {
                log(&format!("retired {}", previous));
            }
            Err(e) => {
                // Distinguish "tor no longer knows this service" (clearing is
                // correct) from "we could not authenticate / could not reach the
                // control port" (clearing would erase the only record of a
                // service that may still be live). Round 4: the old code cleared
                // on ANY failure, which destroyed state after an auth error.
                let already_gone = e.contains("552") || e.to_lowercase().contains("unknown service");
                if already_gone {
                    log(&format!(
                        "DEL_ONION {} reports the service is already gone ({}): clearing state",
                        previous, e
                    ));
                } else {
                    eprintln!(
                        "FAIL({}): DEL_ONION {} failed ({}): keeping state — the service may still be live; fix authentication and retry",
                        EXIT_FAIL, previous, e
                    );
                    std::process::exit(EXIT_FAIL);
                }
            }
        }
        let cleared = apply_retire(&st);
        if let Err(e) = cleared.save(state_path) {
            eprintln!("FAIL({}): save state: {}", EXIT_FAIL, e);
            std::process::exit(EXIT_FAIL);
        }
    } else {
        log(&format!("dry-run: would DEL_ONION {}", previous));
    }
}

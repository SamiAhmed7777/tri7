//! tri7-onion-rotate — the node's Tor v3 onion LIFECYCLE daemon
//! (BRIEF_TOR_V2 item 5; round-2 hold + period gate; round-3 daemon model).
//!
//! LIFECYCLE DAEMON (`--hold`, what the shipped unit runs): runs until
//! killed, and NEVER exits because a rotation is due.
//!   1. On startup it ALWAYS re-establishes every stored service — the
//!      current one and, while its grace window is open, the previous one —
//!      from their stored private keys (`ADD_ONION Key=ED25519-V3:<base64>`
//!      on control connections this process keeps open). A restart after a
//!      tor crash brings the onions straight back, whether or not a rotation
//!      is due. With no state file yet it bootstraps the FIRST current
//!      service; if the stored current has NO key (nothing to re-establish
//!      — a round-1 state file or tor with key disclosure off) it rotates
//!      immediately to restore service.
//!   2. Every HOLD_TICK_SECS it probes the held connections (`GETINFO`).
//!      A dead connection (tor restart) is re-established from the stored
//!      key on the next tick. The `AUTHENTICATE` line is rebuilt per NEW
//!      control connection — tor regenerates its control cookie on restart,
//!      so the credential is re-read at connect time, never cached
//!      (round 4).
//!   3. Every tick it plans with the pure `plan_tick`: past `grace_until`
//!     the previous service is `DEL_ONION`ed and cleared (previous AND
//!     previous_key) from the state; when `rotation_due` the daemon rotates
//!     IN-PROCESS — `ADD_ONION` a new service on a kept connection, promote
//!     current → previous TOGETHER WITH current_key → previous_key (the
//!     outgoing current's connection simply becomes the previous's
//!     connection, so the old address never blinks), persist the new state,
//!     print the signed announcement, and carry on. No exit.
//!   4. On every transition it logs the ACTUAL list of addresses it is
//!     serving (from live probes — `SERVING`/`NOT SERVING`, never a claim).
//!
//! The ed25519 HS key is Tor's business — generated by `ADD_ONION
//! NEW:ED25519-V3` or re-established from the stored key; the only key
//! material created in Rust is the node IDENTITY key (secp256k1, existing
//! crate) that signs rotation announcements.
//!
//! ONE-SHOT mode (no `--hold`) stays for operators: perform at most one
//! rotation and exit. The period gate applies (`rotation_gate`): a not-due
//! rotation is refused (exit 0, "rotation not due until <date>") unless
//! `--force`. The new `ADD_ONION` service is EPHEMERAL — it dies when this
//! process exits; the daemon's next startup re-establishes it from the
//! stored key, or use a persistent torrc `HiddenServiceDir` +
//! `--hostname-file` (tor keeps the key on disk; no holder needed).
//!
//! `--retire` remains a one-shot: `DEL_ONION` the previous address only
//! AFTER the grace window has lapsed (refused, exit 0, while it is open).
//! The daemon path does not depend on it — it retires on its own tick.

use tri7_core::onion::{
    self, add_onion_line, add_onion_with_key_line, apply_retire, apply_rotation,
    load_or_create_identity, open_control, plan_startup, plan_tick, private_key_from_reply,
    read_hostname_file, rotation_gate, service_id_from_reply, serving_set, sign_announcement,
    startup_needs_rotation, verify_announcement, AuthSource, ControlConn, OnionState,
    RotationAnnouncement, ServiceToServe, DEFAULT_CONTROL_ADDR, DEFAULT_GRACE_DAYS,
    ONION_SERVICE_PORT,
};

const EXIT_USAGE: i32 = 2;
const EXIT_FAIL: i32 = 1;
/// Daemon cadence: probe the held control connections and run one
/// `plan_tick` a minute (cheap `GETINFO`, detects a tor restart within the
/// minute instead of silently claiming services that are gone).
const HOLD_TICK_SECS: u64 = 60;

fn usage() -> ! {
    eprintln!(
        "usage: tri7-onion-rotate --state-dir DIR [--grace-days N]\n\
         \x20        [--control IP:PORT] [--cookie PATH|--password PW] [--port N]\n\
         \x20        [--hostname-file PATH] [--hold] [--force] [--retire] [--dry-run]\n\
         \n\
         Manages the node's Tor v3 onion via the control port (default {}):\n\
         re-establishes the stored services from their keys, rotates when the\n\
         {}-day period is due, keeps the previous address for the grace\n\
         window (default {} days) and prints signed announcements.\n\
         --hold                LIFECYCLE DAEMON (what the systemd unit runs):\n\
                               always re-establish the stored current and\n\
                               in-grace previous services from their stored\n\
                               keys, then rotate IN-PROCESS on its own tick\n\
                               when due — never exits for being due\n\
         --force               one-shot: rotate even when the period is not\n\
                               due (makes no sense with --hold)\n\
         --retire              one-shot: DEL_ONION the previous address\n\
                               after the grace window and drop it from the\n\
                               state (the daemon does this itself on its\n\
                               tick; this is for one-shot leftovers)\n\
         --hostname-file PATH  one-shot: read the address from a Tor\n\
                               <HiddenServiceDir>/hostname file instead of\n\
                               ADD_ONION (persistent/torrc-managed services\n\
                               — they survive reboots without a daemon)\n\
         --dry-run             one-shot: connect and report, change nothing\n",
        DEFAULT_CONTROL_ADDR,
        onion::ROTATION_PERIOD_DAYS,
        DEFAULT_GRACE_DAYS
    );
    std::process::exit(EXIT_USAGE);
}

struct Args {
    state_dir: Option<std::path::PathBuf>,
    grace_days: u64,
    control: String,
    password: Option<String>,
    cookie: Option<std::path::PathBuf>,
    port: u16,
    hostname_file: Option<std::path::PathBuf>,
    hold: bool,
    force: bool,
    retire: bool,
    dry_run: bool,
}

fn parse_args() -> Args {
    let mut a = Args {
        state_dir: None,
        grace_days: DEFAULT_GRACE_DAYS,
        control: DEFAULT_CONTROL_ADDR.to_string(),
        password: None,
        cookie: None,
        port: ONION_SERVICE_PORT,
        hostname_file: None,
        hold: false,
        force: false,
        retire: false,
        dry_run: false,
    };
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut i = 0;
    while i < args.len() {
        let need = |i: &mut usize, args: &[String]| -> String {
            *i += 1;
            match args.get(*i) {
                Some(v) => v.clone(),
                None => usage(),
            }
        };
        match args[i].as_str() {
            "--state-dir" => a.state_dir = Some(std::path::PathBuf::from(need(&mut i, &args))),
            "--grace-days" => {
                a.grace_days = need(&mut i, &args).parse().unwrap_or_else(|_| usage())
            }
            "--control" => a.control = need(&mut i, &args),
            "--password" => a.password = Some(need(&mut i, &args)),
            "--cookie" => a.cookie = Some(std::path::PathBuf::from(need(&mut i, &args))),
            "--port" => a.port = need(&mut i, &args).parse().unwrap_or_else(|_| usage()),
            "--hostname-file" => {
                a.hostname_file = Some(std::path::PathBuf::from(need(&mut i, &args)))
            }
            "--hold" => a.hold = true,
            "--force" => a.force = true,
            "--retire" => a.retire = true,
            "--dry-run" => a.dry_run = true,
            "--help" | "-h" => usage(),
            other => {
                eprintln!("unknown argument {}", other);
                usage();
            }
        }
        i += 1;
    }
    // NOTE: `cookie` stays EXPLICIT-only here (round-4 defect 3). The
    // auto-discovered cookie and the precedence
    // explicit --cookie > explicit --password > auto cookie > bare
    // are resolved by resolve_auth_source in main(); installing the default
    // cookie here used to override an explicit --password and made an
    // unreadable auto cookie fatal.
    if a.state_dir.is_none() {
        eprintln!("--state-dir DIR is required");
        usage();
    }
    if a.hold && a.hostname_file.is_some() {
        eprintln!("--hold applies to ephemeral ADD_ONION services; a --hostname-file service is torrc-managed and already persistent — do not combine them");
        usage();
    }
    if a.hold && a.dry_run {
        eprintln!("--hold holds real services open; it makes no sense with --dry-run (nothing is created)");
        usage();
    }
    if a.hold && a.force {
        eprintln!("--hold is the lifecycle daemon: it re-establishes the stored services and rotates in-process when due; --force is the ONE-SHOT early-rotation override — run without --hold to rotate early");
        usage();
    }
    a
}

fn now_secs() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

fn log(msg: &str) {
    println!("[onion-rotate] {}", msg);
}

/// Build the AUTHENTICATE line for ONE new control connection from the
/// resolved auth source (round-4 defect 1: per connection, never cached —
/// tor regenerates the cookie when it restarts, so a line built once at
/// process start would authenticate with stale bytes forever). An
/// unreadable AUTO-discovered cookie falls back to bare AUTHENTICATE and
/// the fallback is LOGGED (round-4 defect 3); an explicitly requested
/// cookie that cannot be read is a hard `Err`.
fn auth_for_connection(src: &AuthSource) -> Result<String, String> {
    let (line, fallback) = src.auth_line()?;
    if let Some(w) = fallback {
        log(&format!(
            "auto-discovered cookie unreadable ({}) — falling back to bare AUTHENTICATE",
            w
        ));
    }
    Ok(line)
}

fn identity_or_exit(state_dir: &std::path::Path) -> ([u8; 32], String) {
    match load_or_create_identity(state_dir) {
        Ok(x) => x,
        Err(e) => {
            eprintln!("FAIL({}): identity key: {}", EXIT_FAIL, e);
            std::process::exit(EXIT_FAIL);
        }
    }
}

fn main() {
    let args = parse_args();
    let state_dir = args.state_dir.clone().unwrap();
    let state_path = state_dir.join("onion-state.json");
    let now = now_secs();

    // Resolve the auth SOURCE once (round-4 defect 3 precedence: explicit
    // --cookie > explicit --password > auto-discovered cookie > bare); the
    // AUTHENTICATE line itself is rebuilt at every connect via
    // auth_for_connection — a line read once here would go stale after a
    // tor restart (round-4 defect 1).
    let auth_src = onion::resolve_auth_source(
        args.cookie.as_deref(),
        args.password.as_deref(),
        onion::default_cookie_path,
    );
    // An EXPLICITLY requested cookie that cannot be read is a hard error,
    // up front (an auto cookie failing is NOT: it falls back per
    // connection, with a log line).
    if let AuthSource::Cookie(p) = &auth_src {
        if let Err(e) = onion::cookie_auth_line(p) {
            eprintln!("FAIL({}): {}", EXIT_FAIL, e);
            std::process::exit(EXIT_FAIL);
        }
        log(&format!("control auth: cookie {}", p.display()));
    }

    if args.retire {
        retire(&args, &auth_src, &state_path, now);
        return;
    }
    if args.hold {
        hold_daemon(&args, &auth_src, &state_dir, &state_path);
        return;
    }

    // ---- one-shot rotation (operator tooling; the unit runs --hold) ----
    if let Err(e) = std::fs::create_dir_all(&state_dir) {
        eprintln!("FAIL({}): create_dir_all {}: {}", EXIT_FAIL, state_dir.display(), e);
        std::process::exit(EXIT_FAIL);
    }
    let (secret, pub_hex) = identity_or_exit(&state_dir);
    let old = OnionState::load(&state_path);

    // Round 2 item 3: the period is ENFORCED for one-shot runs. A not-due
    // rotation is refused (exit 0, clear "not due until <date>" line)
    // unless --force. The daemon path (above) does not use this gate for
    // startup — it only re-establishes there; rotation happens on its tick.
    if let Some(st) = &old {
        if let Err(msg) = rotation_gate(now, st.rotated_at, onion::ROTATION_PERIOD_DAYS, args.force)
        {
            log(&msg);
            return;
        }
    }

    // New address: a torrc hostname file (persistent — no connection) or an
    // ephemeral ADD_ONION whose connection is DROPPED at exit (the daemon
    // re-establishes it from the stored key later).
    let (new_addr, new_key): (String, Option<String>) = if let Some(hf) = &args.hostname_file {
        match read_hostname_file(hf) {
            Ok(a) => (a, None),
            Err(e) => {
                eprintln!("FAIL({}): {}", EXIT_FAIL, e);
                std::process::exit(EXIT_FAIL);
            }
        }
    } else {
        // the ONE connection this one-shot opens: auth line built NOW
        let auth = match auth_for_connection(&auth_src) {
            Ok(a) => a,
            Err(e) => {
                eprintln!("FAIL({}): {}", EXIT_FAIL, e);
                std::process::exit(EXIT_FAIL);
            }
        };
        match onion::create_onion_with_auth(&args.control, &auth, args.port) {
            Ok((id, addr, key)) => {
                log(&format!("ADD_ONION ok: ServiceID {}", id));
                if key.is_none() {
                    log("ADD_ONION reply carried no PrivateKey — this address CANNOT be re-established by a later daemon start (torrc HiddenServiceDir is the persistent alternative)");
                }
                (addr, key)
            }
            Err(e) => {
                eprintln!("FAIL({}): ADD_ONION: {}", EXIT_FAIL, e);
                std::process::exit(EXIT_FAIL);
            }
        }
    };

    // The pure transition pairs the outgoing current with ITS key as the
    // new previous (round 3, defect 1).
    let grace_until = now + args.grace_days.saturating_mul(86_400);
    let st = match &old {
        Some(o) => {
            let mut s = apply_rotation(o, new_addr.clone(), new_key.clone(), now, args.grace_days);
            s.identity_pub = pub_hex.clone();
            s
        }
        None => OnionState {
            current: new_addr.clone(),
            previous: None,
            rotated_at: now,
            grace_until,
            identity_pub: pub_hex.clone(),
            current_key: new_key.clone(),
            previous_key: None,
        },
    };
    log(&format!("new onion: {}", st.current));

    // signed announcement: proof the old address moved to the new one
    let mut ann = RotationAnnouncement {
        identity_pub: pub_hex.clone(),
        old_onion: st.previous.clone().unwrap_or_else(|| st.current.clone()),
        new_onion: st.current.clone(),
        epoch: now,
        valid_from: now,
        valid_until: grace_until,
        sig: String::new(),
    };
    if let Err(e) = sign_announcement(&secret, &mut ann) {
        eprintln!("FAIL({}): sign announcement: {}", EXIT_FAIL, e);
        std::process::exit(EXIT_FAIL);
    }
    if let Err(e) = verify_announcement(&ann, Some(now)) {
        eprintln!("FAIL({}): self-verify announcement: {}", EXIT_FAIL, e);
        std::process::exit(EXIT_FAIL);
    }

    if !args.dry_run {
        if let Err(e) = st.save(&state_path) {
            eprintln!("FAIL({}): save state: {}", EXIT_FAIL, e);
            std::process::exit(EXIT_FAIL);
        }
        log(&format!("state written: {}", state_path.display()));
    } else {
        log("dry-run: state not written, onion NOT persisted");
    }
    println!(
        "{}",
        serde_json::to_string_pretty(&ann).unwrap_or_else(|_| "{}".into())
    );
    println!("ANNOUNCE {} {}", st.current, ann.sig);

    if args.hostname_file.is_none() {
        log("NOTE: one-shot mode — the ADD_ONION service dies when this process exits; the daemon (systemd unit, --hold) re-establishes it from the stored key on its next start, or use a persistent torrc HiddenServiceDir + --hostname-file");
    }
}

